// Downloads the site's Google Fonts (latin + latin-ext subsets) into assets/fonts/ and writes src/styles/fonts.css.
// The fonts are open-licence (SIL OFL), so self-hosting is allowed. Re-run only if the font list changes:
//   node tools/fetch-fonts.mjs && node tools/bundle-css.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const outDir = path.join(root, "assets/fonts");
const CSS_URL = "https://fonts.googleapis.com/css2?family=Bodoni+Moda:opsz,wght@6..96,400;6..96,500&family=Corinthia&family=Gilda+Display&family=Pinyon+Script&display=swap";
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";
const KEEP = new Set(["latin", "latin-ext"]);

const css = await (await fetch(CSS_URL, { headers: { "user-agent": UA } })).text();
// Blocks look like: /* latin */\n@font-face { ... }
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g)];
if (!blocks.length) throw new Error("Unexpected Google Fonts response");

fs.mkdirSync(outDir, { recursive: true });
let outCss = "/* Self-hosted fonts (SIL Open Font License). Generated by tools/fetch-fonts.mjs — do not edit by hand. */\n";
const seen = new Map();
for (const [, subset, face] of blocks) {
  if (!KEEP.has(subset)) continue;
  const family = face.match(/font-family:\s*'([^']+)'/)[1];
  const weight = (face.match(/font-weight:\s*([^;]+);/) || [, "400"])[1].trim();
  const src = face.match(/url\((https:[^)]+\.woff2)\)/)[1];
  let file = seen.get(src);
  if (!file) {
    file = `${family.toLowerCase().replace(/\s+/g, "-")}-${subset}.woff2`;
    if ([...seen.values()].includes(file)) file = file.replace(".woff2", `-${weight.replace(/\s+/g, "-")}.woff2`);
    const buf = Buffer.from(await (await fetch(src)).arrayBuffer());
    fs.writeFileSync(path.join(outDir, file), buf);
    seen.set(src, file);
    console.log(`${file}  ${(buf.length / 1024).toFixed(1)} KB`);
  }
  outCss += `/* ${subset} */\n` + face.replace(/url\(https:[^)]+\)/, `url("../../assets/fonts/${file}")`) + "\n";
}
fs.writeFileSync(path.join(root, "src/styles/fonts.css"), outCss);
console.log("Wrote src/styles/fonts.css");
